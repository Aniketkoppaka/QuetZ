class MockLLMClient:
    """
    Deterministic in-memory mock client for offline testing and repair-loop simulation.
    """

    def __init__(
        self,
        responses: list[str | LLMResponse | Callable[[list[LLMMessage]], str]] | None = None,
    ) -> None:
        self._responses = list(responses) if responses else []
        self._call_history: list[list[LLMMessage]] = []

    @property
    def call_history(self) -> list[list[LLMMessage]]:
        """History of message lists passed to generate()."""
        return self._call_history

    def add_response(self, response: str | LLMResponse | Callable[[list[LLMMessage]], str]) -> None:
        """Enqueue a canned response or response generator."""
        self._responses.append(response)

    def generate(
        self,
        messages: list[LLMMessage] | tuple[LLMMessage, ...],
        config: LLMConfig,
        response_schema: type[BaseModel] | None = None,
    ) -> LLMResponse:
        """Pop next canned response or execute generator."""
        msg_list = list(messages)
        self._call_history.append(msg_list)

        if not self._responses:
            # Fallback default minimal empty JSON plan
            return LLMResponse(
                content="{}",
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 10},
                latency_ms=1.0,
            )

        resp = self._responses.pop(0)

        if callable(resp):
            content_str = resp(msg_list)
            return LLMResponse(
                content=content_str,
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 50},
                latency_ms=1.0,
            )
        elif isinstance(resp, LLMResponse):
            return resp
        else:
            return LLMResponse(
                content=str(resp),
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 50},
                latency_ms=1.0,
            )


