"""
agents/llm_client.py -- Provider-neutral LLM client abstraction and test mocks.

Provides a decoupled interface for interacting with LLM backends with strict
structured-output support, offline mock capabilities, and zero external SDK dependencies.
"""
from __future__ import annotations

import json
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from typing import Any, Callable, Protocol, runtime_checkable
from pydantic import BaseModel, ConfigDict, Field


class LLMMessage(BaseModel):
    """A single chat message exchanged with an LLM."""

    model_config = ConfigDict(frozen=True)

    role: str = Field(description="Role: 'system', 'user', or 'assistant'")
    content: str = Field(description="Message body text")


class LLMConfig(BaseModel):
    """Configuration parameters for LLM generation."""

    model_config = ConfigDict(frozen=True)

    model: str = Field(default="gpt-4o-mini", description="Model identifier")
    temperature: float = Field(default=0.0, ge=0.0, le=2.0, description="Sampling temperature")
    seed: int | None = Field(default=42, description="Random seed for reproducible generation")
    timeout_seconds: float = Field(default=60.0, ge=1.0, description="Network timeout in seconds")
    max_tokens: int | None = Field(default=4000, ge=1, description="Maximum completion tokens")


class LLMResponse(BaseModel):
    """Structured response returned by an LLM backend."""

    model_config = ConfigDict(frozen=True)

    content: str = Field(description="Raw text content generated by the model")
    model: str = Field(description="Model identifier that produced the response")
    usage: dict[str, Any] = Field(default_factory=dict, description="Token usage statistics")
    latency_ms: float = Field(default=0.0, ge=0.0, description="End-to-end request latency in ms")
    raw_response: dict[str, Any] = Field(default_factory=dict, description="Raw provider response payload")


@runtime_checkable
class LLMClientInterface(Protocol):
    """Protocol for LLM clients consumed by the planning agent."""

    def generate(
        self,
        messages: list[LLMMessage] | tuple[LLMMessage, ...],
        config: LLMConfig,
        response_schema: type[BaseModel] | None = None,
    ) -> LLMResponse:
        """
        Generate a completion given a sequence of messages and configuration.

        Args:
            messages: List of system, user, and assistant messages.
            config: LLM generation parameters (temperature, model, etc.).
            response_schema: Optional Pydantic model for structured JSON output.

        Returns:
            LLMResponse with generated content and metadata.
        """
        ...


class MockLLMClient:
    """
    Deterministic in-memory mock client for offline testing and repair-loop simulation.
    """

    def __init__(
        self,
        responses: list[str | LLMResponse | Callable[[list[LLMMessage]], str]] | None = None,
    ) -> None:
        self._responses = list(responses) if responses else []
        self._call_history: list[list[LLMMessage]] = []

    @property
    def call_history(self) -> list[list[LLMMessage]]:
        """History of message lists passed to generate()."""
        return self._call_history

    def add_response(self, response: str | LLMResponse | Callable[[list[LLMMessage]], str]) -> None:
        """Enqueue a canned response or response generator."""
        self._responses.append(response)

    def generate(
        self,
        messages: list[LLMMessage] | tuple[LLMMessage, ...],
        config: LLMConfig,
        response_schema: type[BaseModel] | None = None,
    ) -> LLMResponse:
        """Pop next canned response or execute generator."""
        msg_list = list(messages)
        self._call_history.append(msg_list)

        if not self._responses:
            # Fallback default minimal empty JSON plan
            return LLMResponse(
                content="{}",
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 10},
                latency_ms=1.0,
            )

        resp = self._responses.pop(0)

        if callable(resp):
            content_str = resp(msg_list)
            return LLMResponse(
                content=content_str,
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 50},
                latency_ms=1.0,
            )
        elif isinstance(resp, LLMResponse):
            return resp
        else:
            return LLMResponse(
                content=str(resp),
                model=config.model,
                usage={"prompt_tokens": 100, "completion_tokens": 50},
                latency_ms=1.0,
            )


class HttpLLMClient:
    """
    Zero-dependency HTTP client for OpenAI-compatible /chat/completions endpoints.
    Uses standard library urllib.request.
    """

    def __init__(
        self,
        api_base_url: str = "https://api.openai.com/v1",
        api_key: str = "",
    ) -> None:
        self._api_base_url = api_base_url.rstrip("/")
        self._api_key = api_key

    def generate(
        self,
        messages: list[LLMMessage] | tuple[LLMMessage, ...],
        config: LLMConfig,
        response_schema: type[BaseModel] | None = None,
    ) -> LLMResponse:
        """Execute chat completion request with JSON response formatting."""
        endpoint = f"{self._api_base_url}/chat/completions"

        payload: dict[str, Any] = {
            "model": config.model,
            "messages": [{"role": m.role, "content": m.content} for m in messages],
            "temperature": config.temperature,
        }

        if config.seed is not None:
            payload["seed"] = config.seed
        if config.max_tokens is not None:
            payload["max_tokens"] = config.max_tokens

        # Structured output constraint
        if response_schema is not None:
            schema_dict = response_schema.model_json_schema()
            payload["response_format"] = {
                "type": "json_schema",
                "json_schema": {
                    "name": response_schema.__name__,
                    "strict": True,
                    "schema": schema_dict,
                },
            }
        else:
            payload["response_format"] = {"type": "json_object"}

        headers = {
            "Content-Type": "application/json",
        }
        if self._api_key:
            headers["Authorization"] = f"Bearer {self._api_key}"

        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(endpoint, data=data_bytes, headers=headers, method="POST")

        start_time = time.perf_counter()
        try:
            with urllib.request.urlopen(req, timeout=config.timeout_seconds) as response:
                latency_ms = round((time.perf_counter() - start_time) * 1000, 2)
                resp_json = json.loads(response.read().decode("utf-8"))
                choice = resp_json.get("choices", [{}])[0]
                content = choice.get("message", {}).get("content", "")
                usage = resp_json.get("usage", {})
                return LLMResponse(
                    content=content,
                    model=resp_json.get("model", config.model),
                    usage=usage,
                    latency_ms=latency_ms,
                    raw_response=resp_json,
                )
        except urllib.error.HTTPError as e:
            err_body = e.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"HTTP LLM request failed with status {e.code}: {err_body}") from e
        except Exception as e:
            raise RuntimeError(f"LLM request error: {e}") from e